def is_interest_reply(question, history):
    """Recognize a short preference reply after the assistant asks what the learner likes."""
    if not history:
        return False
    last = history[-1]
    if last.get("role") != "assistant":
        return False
    previous = str(last.get("content") or "")
    q = "".join(str(question or "").casefold().split())
    asked_for_interest = any(term in previous for term in ("ชอบอะไร", "ชอบงานแบบไหน", "สนใจด้านไหน", "สิ่งที่ชอบ", "ความสนใจ"))
    has_interest = any(term in q for _, terms in _INTERESTS for term in terms)
    return asked_for_interest and has_interest


def matching_programs(question, max_items=6):
    q = "".join(str(question or "").casefold().split())
    matched_groups = [
        group for group, terms in _INTERESTS
        if any(term.casefold() in q for term in terms)
    ]
    degree_filter = "ปวช" if "ปวช" in q else ("ปวส" if "ปวส" in q else "")
    selected = [
        item for item in PROGRAMS
        if (not matched_groups or item["group"] in matched_groups)
        and (not degree_filter or degree_filter in item["name"])
    ]
    return (selected[:max_items] if max_items else selected), matched_groups


